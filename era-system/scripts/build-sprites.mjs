#!/usr/bin/env node
/**
 * Builds pixel sprites for a sprite-kind era.
 *
 *   in:  styles/eras/<era>.sprites.json        (era data — palette + pixel maps)
 *   out: public/sprites/<era>/*.svg            (crisp, pixel-aligned SVGs)
 *        styles/eras/<era>.sprites.css         (generated frame-control rules)
 *
 * Components never see a hex value: they render
 *   <button class="frame-control" data-fill="action">
 * and the era's generated CSS supplies the sprite.
 *
 * Usage:  node scripts/build-sprites.mjs 1995
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const era = process.argv[2];
if (!era) { console.error('Usage: node scripts/build-sprites.mjs <era>'); process.exit(1); }

const spec = JSON.parse(fs.readFileSync(path.join(root, 'styles', 'eras', `${era}.sprites.json`), 'utf8'));
const outDir = path.join(root, 'public', 'sprites', era);
fs.mkdirSync(outDir, { recursive: true });

/* ── colour ─────────────────────────────────────────────── */
const mix = (hex, target, amt) => {
  const h = i => parseInt(hex.slice(i, i + 2), 16), t = i => parseInt(target.slice(i, i + 2), 16);
  const c = (a, b) => Math.round(a + (b - a) * amt).toString(16).padStart(2, '0');
  return ('#' + c(h(1), t(1)) + c(h(3), t(3)) + c(h(5), t(5))).toUpperCase();
};
/** "+0.38" lightens base, "-0.45" darkens base, "#HEX" is literal. */
const resolve = (v, base) =>
  typeof v === 'string' && /^[+-]/.test(v)
    ? mix(base, v[0] === '+' ? '#FFFFFF' : '#000000', Math.abs(parseFloat(v)))
    : v.toUpperCase();

function tones(fill, state) {
  const face0 = fill.face;
  const hi = resolve(fill.hi, face0);
  const shade = resolve(fill.shade, face0);
  let face = face0, H = hi, S = shade;
  if (state === 'hover') face = fill.hover ? fill.hover.toUpperCase() : resolve(spec.states.hover.face, face0);
  if (state === 'sunk') {
    face = resolve(spec.states.sunk.face, face0);
    if (spec.states.sunk.swap) [H, S] = [shade, hi];
  }
  return { '.': null, D: fill.outline.toUpperCase(), H, S, F: face };
}

/* ── svg ────────────────────────────────────────────────── */
function svg(map, palette, scale) {
  const w = map[0].length * scale, h = map.length * scale;
  const byColour = {};
  map.forEach((row, r) => [...row].forEach((ch, q) => {
    const col = palette[ch];
    if (!col) return;
    (byColour[col] ??= []).push(`M${q * scale} ${r * scale}h${scale}v${scale}h-${scale}z`);
  }));
  const paths = Object.entries(byColour).map(([c, d]) => `<path fill="${c}" d="${d.join('')}"/>`).join('');
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}" shape-rendering="crispEdges">${paths}</svg>`;
}

const written = [];
const write = (name, content) => { fs.writeFileSync(path.join(outDir, name), content); written.push(name); };
const url = name => `url(/sprites/${era}/${name})`;
const E = `[data-era="${era}"]`;
const css = [];

css.push(`/* GENERATED by scripts/build-sprites.mjs from ${era}.sprites.json — do not edit by hand */\n`);
css.push(`${E} .frame-control {\n  border-style: solid;\n  border-color: transparent;\n  background: none;\n}`);

const STATES = ['base', 'hover', 'sunk'];
const sel = (fill, extra = '', ctx = '') => `${E} ${ctx}.frame-control[data-fill="${fill}"]${extra}`;

function emitFill(name, fill, ctx = '', suffix = '') {
  const scales = fill.scales ?? [4];
  scales.forEach((s, i) => {
    const size = i === 0 ? '' : '[data-size="lg"]';
    const bw = s * 2;
    const states = name === 'disabled' ? ['base'] : STATES;
    for (const st of states) write(`${name}${suffix}-${st}-${s}.svg`, svg(spec.map, tones(fill, st), s));

    css.push(`${sel(name, size, ctx)} {\n  border-width: ${bw}px;\n  border-image: ${url(`${name}${suffix}-base-${s}.svg`)} ${bw} fill stretch;\n}`);
    if (name !== 'disabled') {
      css.push(`${sel(name, size + ':hover', ctx)},\n${sel(name, size + '[data-state="hover"]', ctx)} {\n  border-image-source: ${url(`${name}${suffix}-hover-${s}.svg`)};\n}`);
      css.push(`${sel(name, size + ':active', ctx)},\n${sel(name, size + '[data-state="pressed"]', ctx)} {\n  border-image-source: ${url(`${name}${suffix}-sunk-${s}.svg`)};\n}`);
    }
  });
}

for (const [name, fill] of Object.entries(spec.fills)) emitFill(name, fill);

// variants on --bg-inverse bookends: outlines lighten or the component dissolves
for (const [name, over] of Object.entries(spec.inverse ?? {})) {
  const base = spec.fills[name];
  emitFill(name, { ...base, ...over, scales: [base.scales[0]] }, '.bookend ', '-inv');
}

// chat bubble tails
// tail size comes from the map; overlap = how many rows cover the bubble's frame ring
// (1 for a single-line frame, 2 for a double-line one). Default 1 keeps older eras unchanged.
const tailW = spec.tail[0].length * 4, tailH = spec.tail.length * 4, tailLap = (spec.tailOverlap ?? 1) * 4;
css.push(`${E} .frame-tail {\n  display: block;\n  width: ${tailW}px;\n  height: ${tailH}px;\n  margin-top: -${tailLap}px;\n  background-size: ${tailW}px ${tailH}px;\n}`);
for (const name of spec.tails ?? []) {
  write(`tail-${name}.svg`, svg(spec.tail, tones(spec.fills[name], 'base'), 4));
  css.push(`${E} .frame-tail[data-fill="${name}"] { background-image: ${url(`tail-${name}.svg`)}; }`);
}

fs.writeFileSync(path.join(root, 'styles', 'eras', `${era}.sprites.css`), css.join('\n\n') + '\n');
console.log(`✓ ${era}: ${written.length} sprites → public/sprites/${era}/`);
console.log(`✓ ${era}: styles/eras/${era}.sprites.css`);
