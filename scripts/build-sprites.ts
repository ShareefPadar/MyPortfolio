/**
 * Pre-renders every sprite to a PNG in /public/sprites/ at build time.
 *
 * Why build time rather than runtime canvas (spec §3.1 note): a static URL
 * means `border-image-source` can live in a CSS class instead of an inline
 * style prop, so every component that uses a sprite stays a server component,
 * and hover/sunk become plain CSS :hover/:active with no JS state.
 *
 * Run: npm run sprites   (wired to prebuild, and the output is committed so a
 * fresh clone can `next dev` without running it first)
 */

import { deflateSync } from "node:zlib";
import { mkdirSync, writeFileSync, readdirSync, rmSync } from "node:fs";
import { join } from "node:path";
import {
  BODY,
  PALETTES,
  PALETTE_NAMES,
  SCALES,
  STATES,
  resolve,
} from "../lib/sprite";

/* ── minimal PNG encoder (8-bit RGBA) ─────────────────────────────── */

const CRC_TABLE = (() => {
  const t = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    t[n] = c >>> 0;
  }
  return t;
})();

function crc32(buf: Buffer): number {
  let c = 0xffffffff;
  for (let i = 0; i < buf.length; i++) c = CRC_TABLE[(c ^ buf[i]) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

function chunk(type: string, data: Buffer): Buffer {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length, 0);
  const typed = Buffer.concat([Buffer.from(type, "ascii"), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(typed), 0);
  return Buffer.concat([len, typed, crc]);
}

function encodePng(width: number, height: number, rgba: Buffer): Buffer {
  const sig = Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]);
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(width, 0);
  ihdr.writeUInt32BE(height, 4);
  ihdr[8] = 8; // bit depth
  ihdr[9] = 6; // colour type: RGBA
  // 10,11,12 = compression, filter, interlace — all 0
  const stride = width * 4;
  const raw = Buffer.alloc((stride + 1) * height);
  for (let y = 0; y < height; y++) {
    raw[y * (stride + 1)] = 0; // filter: none
    rgba.copy(raw, y * (stride + 1) + 1, y * stride, (y + 1) * stride);
  }
  return Buffer.concat([
    sig,
    chunk("IHDR", ihdr),
    chunk("IDAT", deflateSync(raw, { level: 9 })),
    chunk("IEND", Buffer.alloc(0)),
  ]);
}

/* ── render one 6×6 map at a scale ────────────────────────────────── */

const rgb = (hex: string): [number, number, number] => [
  parseInt(hex.slice(1, 3), 16),
  parseInt(hex.slice(3, 5), 16),
  parseInt(hex.slice(5, 7), 16),
];

function render(map: Record<string, string | null>, scale: number): Buffer {
  const size = 6 * scale;
  const rgba = Buffer.alloc(size * size * 4); // transparent by default
  for (let r = 0; r < 6; r++) {
    for (let q = 0; q < 6; q++) {
      const colour = map[BODY[r][q]];
      if (!colour) continue;
      const [R, G, B] = rgb(colour);
      for (let dy = 0; dy < scale; dy++) {
        for (let dx = 0; dx < scale; dx++) {
          const o = ((r * scale + dy) * size + (q * scale + dx)) * 4;
          rgba[o] = R;
          rgba[o + 1] = G;
          rgba[o + 2] = B;
          rgba[o + 3] = 255;
        }
      }
    }
  }
  return encodePng(size, size, rgba);
}

/* ── write them all ───────────────────────────────────────────────── */

const out = join(process.cwd(), "public", "sprites");
mkdirSync(out, { recursive: true });

// Clear stale sprites so a renamed palette can't leave an orphan behind.
for (const f of readdirSync(out)) {
  if (f.endsWith(".png")) rmSync(join(out, f));
}

let count = 0;
let bytes = 0;
for (const name of PALETTE_NAMES) {
  for (const state of STATES) {
    for (const scale of SCALES) {
      const png = render(resolve(PALETTES[name], state), scale);
      writeFileSync(join(out, `${name}-${state}-${scale}.png`), png);
      count++;
      bytes += png.length;
    }
  }
}

/* ── emit the matching CSS ────────────────────────────────────────────
   Generated from the same loop that writes the PNGs, so a class can never
   point at a sprite that doesn't exist. Border width and slice are both
   scale × 2 (spec §3.3). */

const css = `/* GENERATED by scripts/build-sprites.ts — do not edit.
   Run \`npm run sprites\` to regenerate. */

.sp {
  border-style: solid;
  border-color: transparent;
  border-image-repeat: stretch;
  border-image-source: var(--sp-base);
  background: none;
}
.sp:hover:not(:disabled) { border-image-source: var(--sp-hover); }
.sp:active:not(:disabled) { border-image-source: var(--sp-sunk); }
/* A sunk frame is a state, not an interaction: current tab, recessed well,
   pressed. It must not lift on hover. */
.sp-sunk { border-image-source: var(--sp-sunk) !important; }

${SCALES.map(
  (s) => `.sp-s${s} { border-width: ${s * 2}px; border-image-slice: ${s * 2} fill; }`,
).join("\n")}

${PALETTE_NAMES.flatMap((name) =>
  SCALES.map(
    (scale) =>
      `.sp-${name}-${scale} {\n` +
      `  --sp-base: url(/sprites/${name}-base-${scale}.png);\n` +
      `  --sp-hover: url(/sprites/${name}-hover-${scale}.png);\n` +
      `  --sp-sunk: url(/sprites/${name}-sunk-${scale}.png);\n` +
      `}`,
  ),
).join("\n")}
`;

const cssPath = join(process.cwd(), "app", "sprites.generated.css");
writeFileSync(cssPath, css);

console.log(
  `sprites: ${count} PNGs, ${(bytes / 1024).toFixed(1)} KB total → public/sprites/\n` +
    `         ${PALETTE_NAMES.length * SCALES.length} classes → app/sprites.generated.css`,
);
